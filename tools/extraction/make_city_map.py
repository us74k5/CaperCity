"""Turn the decoded original city (extract_all.py's data/city.json) into scripts/rules/city_map.gd.

Usage: python3 -I make_city_map.py <extraction_out_dir> <project_dir>

The game copies the original town 1:1 for now: the same 45 x 40 cells, the same road pieces
(and so the same routes), and every building of every type at its original spot.
"""
import json, os, sys

SRC, PROJECT = sys.argv[1], sys.argv[2]
city = json.load(open(os.path.join(SRC, 'data', 'city.json')))
W, H = city['width'], city['height']

# Original building type index -> Caper City type.
TYPES = ['car_dealer', 'arms', 'pub', 'hotel', 'bank', 'print_shop', 'subway', 'police', 'station', 'casino',
         'playground', 'supermarket', 'harbor', 'loan_shark', 'dept_store', 'villa', 'city_hall', 'airport']

# Terrain from the tile graphic layer (tiles/tile_NNN.png), one letter per cell.
FOREST = {111, 113, 115, 116}
FOREST_EDGE = {109, 110, 112, 114, 117, 118, 119, 120, 127}
TERRAIN = {90: 'w', 107: 'c', 108: 'c', 92: 'o', 106: 'b', 91: 'p', 105: 'p', **{t: 'p' for t in range(121, 127)}}

ROAD_CHARS = '.123456789abcdefg'   # road code 0..16 -> one character

roads, terrain = [], []
for y in range(H):
    rrow, trow = '', ''
    for x in range(W):
        r = city['roads'][y][x]
        t = city['tiles'][y][x]
        rrow += ROAD_CHARS[r]
        if r:
            trow += 'r'
        elif t in FOREST:
            trow += 'T'
        elif t in FOREST_EDGE:
            trow += 't'
        elif 93 <= t <= 104:
            trow += 'p'          # the airport's apron and runway (the terminal is a building)
        else:
            trow += TERRAIN.get(t, '.')
    roads.append(rrow)
    terrain.append(trow)

buildings = []
for b in sorted(city['buildings'], key=lambda e: e['code']):
    x0, y0, x1, y1 = b['bbox']
    cells = sorted((c[0], c[1]) for c in b['cells'])
    full = len(cells) == (x1 - x0 + 1) * (y1 - y0 + 1)
    buildings.append([TYPES[b['type']], x0, y0, x1 - x0 + 1, y1 - y0 + 1, [] if full else [list(c) for c in cells]])
    for cx, cy in cells:
        terrain[cy] = terrain[cy][:cx] + 'B' + terrain[cy][cx + 1:]

def gd_list(rows):
    return '[\n' + ''.join('\t"%s",\n' % r for r in rows) + ']'

out = '''class_name CityMap
## The original town, cell for cell. Generated by tools/extraction/make_city_map.py from the
## decoded city map; don't edit by hand.
##
## ROADS: one character per cell, the original road piece code ("." none, 1-9 then a-g = 1..16):
##   1 NE  2 NW  3 ES  4 SW  5 EW  6 NS  7 NESW  8 NEW  9 ESW  a NES  b NSW
##   c motorway lane, westbound   d eastbound   e southbound   f northbound   g motorway junction
## TERRAIN: r road, B building, . grass, T forest, t edge of a forest, b bushes, w water, c canal,
##   o pond, p paving.
## BUILDINGS: [type, x, y, w, h, cells]; cells lists the occupied cells when the shape isn't a full box.

const W := %d
const H := %d

const ROADS := %s

const TERRAIN := %s

const BUILDINGS := [
%s]
''' % (W, H, gd_list(roads), gd_list(terrain),
       ''.join('\t%s,\n' % json.dumps(b).replace('"', '"') for b in buildings))

dest = os.path.join(PROJECT, 'scripts', 'rules', 'city_map.gd')
open(dest, 'w').write(out)
print('wrote', dest, len(buildings), 'buildings')
